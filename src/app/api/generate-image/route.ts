import { NextRequest, NextResponse } from 'next/server';
import { ImageGenerationRequest, ImageGenerationResponse } from '@/lib/types';

// AI service configuration
const AI_ENDPOINT = 'https://oi-server.onrender.com/chat/completions';
const AI_HEADERS = {
  'CustomerId': 'cus_SI19yrM95BDIk5',
  'Content-Type': 'application/json',
  'Authorization': 'Bearer xxx'
};

export async function POST(request: NextRequest) {
  try {
    const body: ImageGenerationRequest = await request.json();
    
    // Validate required fields
    if (!body.prompt?.trim()) {
      return NextResponse.json({
        success: false,
        error: 'Prompt is required'
      } as ImageGenerationResponse, { status: 400 });
    }

    // Construct enhanced prompt based on selections
    const enhancedPrompt = buildEnhancedPrompt(body);
    
    // Get size dimensions
    const sizeInfo = getSizeInfo(body.size);
    
    console.log('Generating image with prompt:', enhancedPrompt);
    console.log('Using model:', body.model);

    const startTime = Date.now();
    
    // Make request to AI service
    const response = await fetch(AI_ENDPOINT, {
      method: 'POST',
      headers: AI_HEADERS,
      body: JSON.stringify({
        model: body.model,
        messages: [{
          role: 'user',
          content: enhancedPrompt
        }]
      })
    });

    if (!response.ok) {
      const errorText = await response.text();
      console.error('AI API Error:', response.status, errorText);
      return NextResponse.json({
        success: false,
        error: `AI service error: ${response.status}`
      } as ImageGenerationResponse, { status: 500 });
    }

    const aiResult = await response.json();
    const generationTime = Math.round((Date.now() - startTime) / 1000);
    
    // Extract image URL from AI response
    let imageUrl = '';
    
    if (aiResult.choices && aiResult.choices[0]?.message?.content) {
      // For text-based responses that might contain URLs
      const content = aiResult.choices[0].message.content;
      const urlMatch = content.match(/https?:\/\/[^\s]+\.(jpg|jpeg|png|webp|gif)/i);
      imageUrl = urlMatch ? urlMatch[0] : content.trim();
    } else if (aiResult.data && aiResult.data[0]?.url) {
      // For direct image URL responses
      imageUrl = aiResult.data[0].url;
    } else if (typeof aiResult === 'string' && aiResult.startsWith('http')) {
      // For direct URL string responses
      imageUrl = aiResult;
    }

    if (!imageUrl) {
      console.error('No image URL found in AI response:', aiResult);
      return NextResponse.json({
        success: false,
        error: 'No image generated by AI service'
      } as ImageGenerationResponse, { status: 500 });
    }

    // Return successful response
    const result: ImageGenerationResponse = {
      success: true,
      imageUrl: imageUrl,
      metadata: {
        prompt: body.prompt,
        model: getModelDisplayName(body.model),
        style: getStyleDisplayName(body.style),
        dimensions: `${sizeInfo.width}×${sizeInfo.height}`,
        generationTime: generationTime
      }
    };

    return NextResponse.json(result);

  } catch (error) {
    console.error('Image generation error:', error);
    
    return NextResponse.json({
      success: false,
      error: 'Internal server error during image generation'
    } as ImageGenerationResponse, { status: 500 });
  }
}

function buildEnhancedPrompt(request: ImageGenerationRequest): string {
  let prompt = request.prompt.trim();
  
  // Add style enhancement
  const styleEnhancements: Record<string, string> = {
    'photorealistic': ', highly detailed, photorealistic, professional photography, sharp focus',
    'artistic': ', artistic, creative composition, expressive brushstrokes, fine art',
    'cartoon': ', cartoon style, animated, colorful, vibrant, playful illustration',
    'oil-painting': ', oil painting style, thick brushstrokes, classical art technique',
    'watercolor': ', watercolor painting, soft edges, flowing colors, artistic medium',
    'minimalist': ', minimalist design, clean composition, simple elements, elegant',
    'cyberpunk': ', cyberpunk aesthetic, neon lights, futuristic, dark atmosphere, sci-fi'
  };
  
  if (styleEnhancements[request.style]) {
    prompt += styleEnhancements[request.style];
  }
  
  // Add quality enhancement
  const qualityEnhancements: Record<string, string> = {
    'standard': ', good quality',
    'high': ', high quality, detailed, crisp',
    'ultra': ', ultra high quality, extremely detailed, masterpiece, 8k resolution'
  };
  
  if (qualityEnhancements[request.quality]) {
    prompt += qualityEnhancements[request.quality];
  }
  
  return prompt;
}

function getSizeInfo(sizeId: string) {
  const sizes: Record<string, { width: number, height: number }> = {
    'square-512': { width: 512, height: 512 },
    'square-1024': { width: 1024, height: 1024 },
    'portrait': { width: 768, height: 1024 },
    'landscape': { width: 1024, height: 768 },
    'widescreen': { width: 1920, height: 1080 }
  };
  
  return sizes[sizeId] || sizes['square-1024'];
}

function getModelDisplayName(modelId: string): string {
  const modelNames: Record<string, string> = {
    'replicate/black-forest-labs/flux-1.1-pro': 'FLUX 1.1 Pro',
    'replicate/black-forest-labs/flux-schnell': 'FLUX Schnell',
    'image-gen': 'Standard Generator'
  };
  
  return modelNames[modelId] || modelId;
}

function getStyleDisplayName(styleId: string): string {
  const styleNames: Record<string, string> = {
    'photorealistic': 'Photorealistic',
    'artistic': 'Artistic',
    'cartoon': 'Cartoon',
    'oil-painting': 'Oil Painting',
    'watercolor': 'Watercolor',
    'minimalist': 'Minimalist',
    'cyberpunk': 'Cyberpunk'
  };
  
  return styleNames[styleId] || styleId;
}